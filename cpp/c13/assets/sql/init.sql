-- Protocol log
CREATE TABLE log_servers( -- Servers are keyed by hostname and port number
    id INTEGER PRIMARY KEY,
    host TEXT NOT NULL, -- Normalize the host part of the URL
    port INTEGER NOT NULL,
    UNIQUE(host, port)
) STRICT;

CREATE TABLE log_sessions( -- Record when each WebSockets connection was initiated
    id INTEGER PRIMARY KEY,
    server_id INTEGER NOT NULL,
    connect_posix_ms INTEGER NOT NULL,
    FOREIGN KEY(server_id) REFERENCES log_servers(id) ON DELETE RESTRICT
) STRICT;

CREATE TABLE log_wsmessages( -- Raw log of WebSockets text transmissions
    id INTEGER PRIMARY KEY,
    session_id INTEGER NOT NULL,
    time_posix_ms INTEGER NOT NULL,
    direction INTEGER NOT NULL, -- Rx=0, Tx=1, others reserved
    kind INTEGER NOT NULL, -- WsText=0, others reserved
    msg ANY, -- kind=WsText => TEXT NOT NULL, others reserved
    FOREIGN KEY(session_id) REFERENCES log_sessions(id) ON DELETE RESTRICT
) STRICT;

-- Memoization tables. These may be losslessly regenerated by replaying the protocol log.
CREATE TABLE memo_peers( -- Track the first and last witnessed activity from a callsign
    callsign INTEGER PRIMARY KEY,
    firstseen_wsmessage_id INTEGER NOT NULL,
    lastseen_wsmessage_id INTEGER NOT NULL,
    FOREIGN KEY(firstseen_wsmessage_id) REFERENCES log_wsmessages(id) ON DELETE RESTRICT,
    FOREIGN KEY(lastseen_wsmessage_id) REFERENCES log_wsmessages(id) ON DELETE RESTRICT
) STRICT;

CREATE TABLE memo_transmissions( -- List each valid M/R transmission not duplicated by reconnection
    id INTEGER PRIMARY KEY, -- For ordering and temporary use only. Do not use as a permanent key.
    callsign INTEGER NOT NULL,
    origin INTEGER NOT NULL, -- FromOtherCallsign=0, FromMyCallsign=1, others reserved
    --                           FromOtherCallsign   FromMyCallsign
    -- tx_wsmessage_id NULL      normal case         someone else sent or did not flush send record to db
    -- tx_wsmessage_id NOT NULL  (impossible)        normal case
    -- rx_wsmessage_id NULL      (impossible)        did not witness server echo
    -- rx_wsmessage_id NOT NULL  normal case         normal case
    tx_wsmessage_id INTEGER UNIQUE,
    rx_wsmessage_id INTEGER UNIQUE,
    FOREIGN KEY(tx_wsmessage_id) REFERENCES log_wsmessages(id) ON DELETE RESTRICT,
    FOREIGN KEY(rx_wsmessage_id) REFERENCES log_wsmessages(id) ON DELETE RESTRICT
) STRICT;

-- User data
CREATE TABLE user_peers( -- Notes on a particular callsign
    callsign INTEGER PRIMARY KEY,
    mine INTEGER NOT NULL,
    nickname TEXT NOT NULL,
    notes TEXT NOT NULL
) STRICT;

CREATE TABLE user_dictionary( -- The translation dictionary
    signal INTEGER PRIMARY KEY,
    json_ser_order INTEGER UNIQUE,
    descr TEXT NOT NULL,
    fmt_before INTEGER NOT NULL,
    fmt_after INTEGER NOT NULL,
    fmt_break_on_double INTEGER NOT NULL
) STRICT;

CREATE TABLE user_translations( -- A historical ID to word association in the dictionary
    signal INTEGER NOT NULL,
    revision INTEGER NOT NULL,
    mtime_posix_ms INTEGER NOT NULL, -- should be used to squash modifications within a time window
    word TEXT NOT NULL,
    PRIMARY KEY(signal, revision),
    FOREIGN KEY(signal) REFERENCES user_dictionary(signal) ON DELETE RESTRICT
) STRICT, WITHOUT ROWID;
